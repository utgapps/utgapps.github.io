// Writes vex-mechanisms/drive-base-designs.json: the five candidate drive bases whose gear ratio
// can be changed (DESIGNS in tools/library/families/drive-base-modular.mjs), for the page that
// compares them. Every design is verified at every ratio it offers before anything is written:
// held together, nothing clipping, cables reaching, and the wheels turning at the ratio the
// gears say.
//   node tools/export-drive-base-designs.mjs
import { writeFileSync } from "node:fs";
import * as THREE from "three";
import { verifiedVersions } from "./library/drive-base-versions.mjs";
import { DESIGNS } from "./library/families/drive-base-modular.mjs";

const round = (value) => Math.round(value * 1000) / 1000;
const MOTOR_RPM = 120, WHEEL_TRAVEL = 200; // an IQ Smart Motor at full speed; a 200 mm wheel goes 200 mm a turn

const designs = DESIGNS.map((design) => {
  const ratios = verifiedVersions(design);
  const [first] = ratios;
  const { made } = first;
  // Each axle turns with everything on it; the motor's axle at 1, the others at their share.
  const spins = made.axles.map((axle) => {
    const center = new THREE.Vector3().setFromMatrixPosition(axle.handle.matrix);
    const meshes = Math.abs(made.gearHoles.indexOf(axle.hole) - made.gearHoles.indexOf(design.motorHole));
    return { x: round(center.x), y: round(center.y), side: axle.side, motorSize: meshes % 2 === 0, sign: meshes % 2 === 0 ? 1 : -1 };
  });
  const TURNS = new Set(["gear", "wheel", "shaft", "spacer"]);
  const parts = made.build.parts.map((handle, index) => {
    const entry = made.saved[index];
    const part = { id: entry.id, p: entry.p.map(round), q: entry.q.map(round) };
    if (TURNS.has(handle.meta.category)) {
      const spin = spins.findIndex((axle) => Math.abs(axle.x - entry.p[0]) < 1 && Math.abs(axle.y - entry.p[1]) < 1 && Math.sign(entry.p[2]) === axle.side);
      if (spin >= 0) part.spin = spin;
    }
    if (handle.meta.category === "gear") {
      part.gear = spins[part.spin].motorSize ? "motor" : "wheel";
      // Where this gear goes in each version: its size, and its exact place.
      part.versions = ratios.map(({ made: version }) => { const gear = version.saved[index]; return { id: gear.id, p: gear.p.map(round), q: gear.q.map(round) }; });
    }
    if (made.strength.has(index)) part.strong = true;
    return part;
  });

  const box = new THREE.Box3();
  for (const part of parts) box.expandByPoint(new THREE.Vector3(...part.p));
  const count = (test) => made.saved.filter(test).length;
  return {
    key: design.key, title: design.title,
    ratios: ratios.map(({ motorTeeth, made: version }) => {
      const turns = Math.abs(version.ratio);
      return { motorTeeth, wheelTeeth: version.wheelTeeth, turns, inchesPerSecond: round((MOTOR_RPM / 60) * WHEEL_TRAVEL * turns / 25.4) };
    }),
    stats: {
      parts: made.saved.length, pins: count((part) => part.id.startsWith("pin-")), beams: count((part) => part.id.startsWith("beam-")),
      standoffs: count((part) => part.id.startsWith("standoff-")), strengthParts: made.strength.size,
      gearsPerSide: made.gearHoles.length,
    },
    spins, parts,
  };
});

const out = new URL("../../vex-mechanisms/drive-base-designs.json", import.meta.url);
writeFileSync(out, JSON.stringify({ note: "Generated by vex-build-center-app/tools/export-drive-base-designs.mjs. Do not edit.", designs }) + "\n");
for (const design of designs) console.log(design.key, JSON.stringify(design.stats), design.ratios.map((ratio) => `${ratio.motorTeeth}T:${ratio.inchesPerSecond}in/s`).join(" "));
